// A cluster is set up differently from a server. The OpenTelemetry Operator
// runs the collectors: one on every node (a DaemonSet) and one for the
// cluster as a whole (a Deployment). The template's catalog still holds
// plain collector configuration, one file per component and signal; here it
// is merged into the two OpenTelemetryCollector resources instead of being
// copied to conf.d, because the operator takes one configuration each.
const (
	kindVM  = "vm"
	kindK8s = "k8s"

	roleCollector = "collector"
	roleManifest  = "manifest"
	roleGuide     = "guide"

	k8sNamespace = "observability"
	k8sCADir     = "/etc/otelgenie/ca"
)

var k8sCollectors = []string{"node", "cluster"}

// place is the word for a target in text shown to the user.
func place(t *Target) string {
	if t.Kind == kindK8s {
		return "cluster"
	}
	return "server"
}

// hasPlatform reports whether the project includes a kind of cluster.
func (j *Journey) hasPlatform() bool {
	for _, ci := range j.Cat.Components(kindK8s) {
		if ci.Platform && contains(j.In.Components, ci.Name) {
			return true
		}
	}
	return false
}

func yamlDocs(text string) ([]map[string]any, error) {
	dec := yaml.NewDecoder(strings.NewReader(text))
	var docs []map[string]any
	for {
		var d map[string]any
		err := dec.Decode(&d)
		if err == io.EOF {
			return docs, nil
		}
		if err != nil {
			return nil, err
		}
		if d != nil {
			docs = append(docs, d)
		}
	}
}

// mergeConfig merges the way the collector merges its own configuration
// files: maps are combined key by key, anything else is replaced.
func mergeConfig(dst, src map[string]any) {
	for k, v := range src {
		if sm, ok := v.(map[string]any); ok {
			if dm, ok := dst[k].(map[string]any); ok {
				mergeConfig(dm, sm)
				continue
			}
			dm := map[string]any{}
			mergeConfig(dm, sm)
			dst[k] = dm
			continue
		}
		dst[k] = v
	}
}

// collectorManifest builds one OpenTelemetryCollector resource: the
// platform's own resource with the selected configuration merged into it.
// It reports false when nothing selected runs on that collector.
func collectorManifest(entries []*Entry, collector string) (string, bool) {
	var shell *Entry
	for _, e := range entries {
		if e.Role == roleCollector && e.Collector == collector {
			shell = e
			break
		}
	}
	if shell == nil {
		return "", false
	}
	docs, err := yamlDocs(shell.Body)
	if err != nil {
		return "", false
	}
	var spec map[string]any
	for _, d := range docs {
		if d["kind"] == "OpenTelemetryCollector" {
			spec, _ = d["spec"].(map[string]any)
		}
	}
	if spec == nil {
		return "", false
	}

	cfg := map[string]any{}
	env, _ := spec["env"].([]any)
	named := map[string]bool{}
	sources := []string{shell.Path}
	add := func(e *Entry, withConfig bool) {
		if withConfig {
			var m map[string]any
			if yaml.Unmarshal([]byte(e.Body), &m) == nil {
				mergeConfig(cfg, m)
			}
			sources = append(sources, e.Path)
		}
		for _, p := range e.Probes {
			if p.Kind == "pod" && !named[p.Var] {
				named[p.Var] = true
				env = append(env, map[string]any{"name": p.Var, "valueFrom": map[string]any{"fieldRef": map[string]any{"fieldPath": p.Arg}}})
			}
		}
	}
	for _, e := range entries {
		if e.Signal == "base" && (e.Collector == "" || e.Collector == collector) {
			add(e, true)
		}
	}
	// What the platform sets for the whole collector comes after the shared
	// base and before the individual files.
	if own, ok := spec["config"].(map[string]any); ok {
		mergeConfig(cfg, own)
	}
	add(shell, false)
	used := 0
	for _, e := range entries {
		if e.Role == "" && e.Signal != "base" && e.Collector == collector {
			add(e, true)
			used++
		}
	}
	if used == 0 {
		return "", false
	}
	spec["config"] = cfg
	if len(env) > 0 {
		spec["env"] = env
	}

	var b strings.Builder
	b.WriteString("# Generated by otelgenie from " + shell.Path + ".\n# Its configuration is these template files merged in order:\n")
	for _, s := range sources[1:] {
		b.WriteString("#   " + s + "\n")
	}
	for i, d := range docs {
		if i > 0 {
			b.WriteString("---\n")
		}
		raw, _ := yaml.Marshal(d)
		b.Write(raw)
	}
	return b.String(), true
}

// images lists the container images the cluster needs and, when the one-time
// setup says images come through an internal registry, where each one is
// expected there.
func (j *Journey) images() [][2]string {
	registry := strings.TrimRight(strings.TrimSpace(j.Profile.Registry), "/")
	if i := strings.Index(registry, "://"); i >= 0 {
		registry = registry[i+3:]
	}
	if j.Profile.ImageMethod == "none" {
		registry = ""
	}
	var out [][2]string
	for _, a := range j.Man.Artifacts {
		if a.Kind != "image" {
			continue
		}
		dst := ""
		if _, rest, ok := strings.Cut(a.URL, "/"); ok && registry != "" {
			dst = registry + "/" + rest
		}
		out = append(out, [2]string{a.URL, dst})
	}
	return out
}

// needsImage reports whether the project uses an image. An agent image is
// only needed when applications are instrumented at all, and then only for
// the stacks the project chose (every stack, if it was not asked).
func (j *Journey) needsImage(url string) bool {
	for _, a := range j.Man.Artifacts {
		if a.Kind == "image" && a.URL == url && a.Language != "" {
			return contains(j.In.Components, "app") && (len(j.In.Stacks) == 0 || contains(j.In.Stacks, a.Language))
		}
	}
	return true
}

func (j *Journey) operatorArtifact() *Artifact {
	for i, a := range j.Man.Artifacts {
		if a.Kind == "operator" {
			return &j.Man.Artifacts[i]
		}
	}
	return nil
}

// platform is the kind of cluster chosen for a target.
func (j *Journey) platform(t *Target) string {
	for _, e := range j.selectedEntries(t) {
		if e.Role == roleCollector {
			return e.Component
		}
	}
	return ""
}

// generateK8s builds every file for a cluster. Resources that are not
// collectors are copied as written, apart from image addresses when images
// come through an internal registry.
const whenServers = "servers"

// serversBesideCluster reports whether the project has a cluster and also
// something chosen that cannot run in one. Those servers send through the
// cluster's collector rather than to the destination.
func (j *Journey) serversBesideCluster() bool {
	if len(j.platforms()) == 0 {
		return false
	}
	inCluster := map[string]bool{}
	for _, ci := range j.choosable(kindK8s) {
		inCluster[ci.Name] = true
	}
	for _, name := range j.serverComponents() {
		if !inCluster[name] {
			return true
		}
	}
	return false
}

// applies reports whether a file marked for a certain shape of project
// belongs in this one.
func (j *Journey) applies(e *Entry) bool {
	return e.When != whenServers || j.serversBesideCluster()
}

func (j *Journey) generateK8s(t *Target) map[string]string {
	files := map[string]string{}
	entries := j.selectedEntries(t)
	var collectors []string
	for _, c := range k8sCollectors {
		if body, ok := collectorManifest(entries, c); ok {
			files["manifests/20-collector-"+c+".yaml"] = body
			collectors = append(collectors, c)
		}
	}
	for _, e := range entries {
		if e.Role == roleManifest {
			if !j.applies(e) {
				continue
			}
			// Kubernetes does not expand ${env:NAME}, so it is filled in here.
			files["manifests/10-"+e.Component+"-"+path.Base(e.Path)] = fillVars(e.Body, t.Vars)
		}
	}

	var list strings.Builder
	list.WriteString("# Container images this setup needs. With two columns, the second is where\n")
	list.WriteString("# the cluster will pull the image from; it must be there before apply.sh runs.\n")
	for _, im := range j.images() {
		// An agent for a stack the project does not use is not needed in the
		// registry, though the resources still point there.
		needed := j.needsImage(im[0])
		if im[1] == "" {
			if needed {
				list.WriteString(im[0] + "\n")
			}
			continue
		}
		if needed {
			list.WriteString(im[0] + " " + im[1] + "\n")
		}
		for p, body := range files {
			files[p] = strings.ReplaceAll(body, im[0], im[1])
		}
	}
	files["images.txt"] = list.String()

	for _, name := range []string{"discover.sh", "apply.sh", "verify.sh", "rollback.sh"} {
		if body, ok := j.Snap.Files["scripts/"+kindK8s+"/"+name]; ok {
			files[name] = body
		}
	}
	files["discover.items"] = j.discoverItems(t.Kind)
	files["otelcol.env"] = j.envFile(t)
	operator := ""
	if a := j.operatorArtifact(); a != nil {
		operator = a.File
	}
	files["settings.env"] = fmt.Sprintf("NAMESPACE=%s\nPLATFORM=%s\nCOLLECTORS=\"%s\"\nOPERATOR_FILE=%s\n",
		k8sNamespace, j.platform(t), strings.Join(collectors, " "), operator)
	if pem := strings.TrimSpace(j.Profile.CABundle); pem != "" {
		files["ca-bundle.pem"] = pem + "\n"
	}
	j.addRequests(t, files)
	files["RUNBOOK.md"] = j.runbookK8s(t, entries, collectors)
	sealFiles(files)
	return files
}

func (j *Journey) runbookK8s(t *Target, entries []*Entry, collectors []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Telemetry setup for cluster %s\n\n", t.Name)
	fmt.Fprintf(&b, "Project: %s\nEnvironment: %s\nCollector endpoint: %s\nTemplate: %s at %s\nSetup fingerprint: %s\n\n",
		j.In.Project, j.In.Env, j.In.Endpoint, j.Snap.Repo, j.Snap.Commit, ComputeFingerprint(j.Profile, j.Snap, j.Man).Code)
	b.WriteString("## What this sets up\n\n")
	for _, e := range entries {
		if !j.applies(e) {
			continue
		}
		if e.Signal != "base" && e.Role != roleCollector {
			fmt.Fprintf(&b, "- %s\n", e.Title)
		}
	}
	fmt.Fprintf(&b, "\nThe OpenTelemetry Operator runs the collectors (%s) in the namespace %s.\n\n", strings.Join(collectors, ", "), k8sNamespace)
	b.WriteString("## Steps\n\n")
	b.WriteString("Run these on a machine where kubectl (or oc) is logged in to the cluster as an administrator.\n\n")
	b.WriteString("1. bash apply.sh\n   It installs the operator if a copy of its manifest is in this folder, asks for each secret, applies manifests/ and waits for the collectors.\n")
	b.WriteString("2. bash verify.sh\n   It reports whether data is flowing.\n")
	b.WriteString("3. To remove everything apply.sh created except the operator, run: bash rollback.sh\n\n")
	b.WriteString("## Where things are\n\n")
	b.WriteString("- Resources: manifests/ (applied in file name order)\n")
	b.WriteString("- Values and secrets: the Secret otelgenie-env in the namespace " + k8sNamespace + "\n")
	b.WriteString("- Images: images.txt\n")
	b.WriteString("- Logs: kubectl -n " + k8sNamespace + " logs -l app.kubernetes.io/managed-by=opentelemetry-operator\n")
	return b.String()
}

// noteClusterFacts records what discovery means for the steps ahead.
func (j *Journey) noteClusterFacts(now time.Time, t *Target, b *Block) {
	if b.Get("admin") != "yes" {
		j.flag(now, t, "The kubectl login used is not a cluster administrator. Installing needs one.")
	}
	if b.Get("operator") == "none" {
		j.decide(now, t, "The OpenTelemetry Operator is not installed yet; the install step will explain how to add it.")
		if b.Get("cert_manager") != "yes" && b.Get("distro") != "ocp" {
			j.flag(now, t, "cert-manager is not installed. The OpenTelemetry Operator needs it before it can be installed.")
		}
	}
	seen := map[string]bool{}
	for _, e := range j.candidateEntries(t.Kind) {
		for _, p := range e.Probes {
			if p.Kind == "svc" && !seen[p.Arg] && svcAddress(p, b.Get("svc."+p.Arg)) == "" {
				seen[p.Arg] = true
				j.flag(now, t, "No Service named %s was found in the cluster. Collecting from it will fail until it is installed or its address is typed in.", p.Arg)
			}
		}
	}
}

// operatorHint tells the user how to get the operator into this cluster,
// according to the one-time setup.
func (j *Journey) operatorHint(t *Target) []string {
	if t.Facts["distro"] == "ocp" {
		return []string{
			"On OpenShift the operator comes from OperatorHub.",
			"Ask a cluster administrator to install \"Red Hat build of OpenTelemetry\" for all namespaces.",
			"Then run apply.sh again.",
		}
	}
	a := j.operatorArtifact()
	if a == nil {
		return []string{"The template names no OpenTelemetry Operator to install. Ask the template owner to add one, or have a cluster administrator install it."}
	}
	out := []string{
		"The file you need is " + a.File + ". On a machine with internet access it is at " + a.URL,
		"Put it in the folder next to apply.sh. The installer applies it and waits for the operator to start.",
	}
	if t.Facts["cert_manager"] != "yes" {
		out = append(out, "cert-manager must be installed in the cluster first; the operator will not start without it.")
	}
	switch j.Profile.ImageMethod {
	case "none":
		out = append(out, "The cluster pulls the images listed in images.txt directly.")
	default:
		out = append(out, "The images listed in images.txt must be in "+j.Profile.Registry+" first. The second column is the address each is expected at.")
	}
	return out
}

func (j *Journey) explainApplyK8s(v *View, t *Target) {
	a := t.Apply
	switch a.Result {
	case "unreachable":
		v.add("error", "kubectl could not reach the cluster", "Log in again, check that kubectl points at this cluster, and run the installer again.")
	case "need-admin":
		v.add("error", "The kubectl login is not a cluster administrator", "The installer creates cluster-wide roles. Run it logged in as a cluster administrator.")
	case "corrupt-files":
		v.add("error", "The files are incomplete or were changed", "Download the files again, unpack them into an empty folder, and run the installer again.")
	case "missing-operator":
		v.add("error", "The OpenTelemetry Operator is not installed in the cluster", "")
		v.add("list", "Install it, then run the installer again", "", j.operatorHint(t)...)
	case "missing-cert-manager":
		v.add("error", "cert-manager is not installed in the cluster", "The OpenTelemetry Operator needs it. Ask a cluster administrator to install cert-manager, then run the installer again.")
	case "operator-failed":
		v.add("error", "The OpenTelemetry Operator did not start", "If the cluster cannot pull its image, check images.txt.", a.Detail...)
	case "placeholders":
		v.add("error", "Some secrets were not entered", "The installer stopped before creating the collectors because these are still empty. Run it again and type them when asked.", a.Detail...)
	case "rejected":
		v.add("error", "The cluster rejected a resource", "", a.Detail...)
	case "not-ready":
		v.add("error", "The collectors were created but did not become ready", "", a.Detail...)
	default:
		v.add("error", "The installer did not finish", "Result reported: "+a.Result)
	}
	for _, d := range a.Diagnoses {
		v.add("warn", d.Cause, d.Fix)
	}
}

// viewK8s is the screen for a cluster at its current step.
func (j *Journey) viewK8s(v *View, t *Target, now time.Time) {
	folder := j.archiveName(t)
	const where = "On the machine with kubectl"
	switch t.Step {
	case StepDiscover:
		v.Title = "Look at the cluster"
		v.Why = "Before anything is installed, a small script reads a few facts from the cluster through kubectl: which kind of cluster it is, whether the OpenTelemetry Operator is there, and where kube-state-metrics and the metrics server are. It only reads; it changes nothing and prints no secrets."
		v.add("text", "1. Unpack the files on a machine that can reach the cluster", "Download the files for this cluster below. Use a machine where kubectl (or oc on OpenShift) is logged in to it.")
		v.add("command", where, fmt.Sprintf("tar xzf %s.tar.gz", folder))
		v.add("text", "2. Check kubectl points at this cluster, then run the script", "")
		v.add("command", where, fmt.Sprintf("kubectl config current-context && bash %s/discover.sh", folder))
		v.add("text", "3. Paste what it printed", "Copy everything from the line OTELGENIE-DISCOVER down to the line starting END OTELGENIE-DISCOVER.")
		v.Form = Form{Kind: "paste", Label: "Output of discover.sh"}

	case StepConfirm:
		v.Title = "Confirm what to set up on this cluster"
		v.Why = "This is what the script found. Tick the kind of cluster this is and whatever else should be collected from it."
		if t.Facts["admin"] != "yes" {
			v.add("warn", "", "The kubectl login used is not a cluster administrator. You can continue, but the install step needs one.")
		}
		v.add("list", "About this cluster", "",
			"kubectl context: "+t.Facts["host"],
			"Kubernetes version: "+t.Facts["server_version"]+", "+t.Facts["nodes"]+" node(s)",
			"Kind of cluster: "+t.Facts["distro"],
			"OpenTelemetry Operator: "+t.Facts["operator"],
			"cert-manager: "+t.Facts["cert_manager"])
		v.Form = Form{Kind: "confirm", Items: j.confirmItems(t)}

	case StepReview:
		v.Title = "Review what will be installed"
		v.Why = "The files for this cluster are ready. Nothing has been changed in the cluster yet."
		var what, also []string
		for _, e := range j.selectedEntries(t) {
			switch {
			case e.Role == roleManifest:
				also = append(also, e.Title)
			case e.Role == "" && e.Signal != "base":
				what = append(what, e.Title)
			}
		}
		v.add("list", "What will be collected", "", what...)
		how := []string{"The OpenTelemetry Operator runs the collectors in the namespace " + k8sNamespace}
		if _, ok := t.Files["manifests/20-collector-node.yaml"]; ok {
			how = append(how, "A DaemonSet: one collector on every node")
		}
		if _, ok := t.Files["manifests/20-collector-cluster.yaml"]; ok {
			how = append(how, "A Deployment: one collector for the cluster as a whole")
		}
		how = append(how, "Sending to "+j.In.Endpoint+" for "+j.In.Project+" / "+j.In.Env)
		v.add("list", "How it will run", "", how...)
		if len(also) > 0 {
			v.add("list", "Also created", "", also...)
		}
		v.add("list", "Secrets you will type when installing, never here", "", j.secretVars(t)...)
		needs := j.openNeeds(t)
		if len(needs) > 0 {
			var items []string
			for _, n := range needs {
				items = append(items, fmt.Sprintf("%s: %s. A ready-to-send request is in requests/%s-%s.md", n.Component, n.Note, n.Component, n.Name))
			}
			v.add("warn", "Needed from someone else", "These depend on another person. Send them the request file from the download.", items...)
			v.Form = Form{Kind: "choice", Options: []Option{
				{"proceed", "These are already in place. Continue."},
				{"waiting", "I have asked and am waiting. Keep my place."},
			}}
		} else {
			v.Form = Form{Kind: "choice", Options: []Option{{"proceed", "Looks right. Continue."}}}
		}
		if t.WaitingSince != "" {
			v.add("warn", "", "Waiting since "+ago(t.WaitingSince, now)+" for: "+strings.Join(t.WaitingItems, "; ")+".")
			v.Form = Form{Kind: "choice", Options: []Option{{"have", "I have what was needed. Continue."}}}
		}

	case StepApply:
		v.Title = "Install on the cluster"
		v.Why = "This installs the operator if it is missing, stores the settings and secrets in the cluster, creates the collectors and waits for them to start. It needs a cluster administrator. You can run it again safely."
		if days, isStale := j.stale(t, now); isStale {
			v.add("warn", "", fmt.Sprintf("The cluster was last looked at %d days ago. Things may have changed since.", days))
			v.Form = Form{Kind: "choice", Options: []Option{
				{"rediscover", "Look at the cluster again first (recommended)."},
				{"continue", "Continue with what was found then."},
			}}
			break
		}
		if t.Apply != nil && t.Apply.Result != "ok" {
			j.explainApplyK8s(v, t)
		}
		if t.Facts["operator"] == "none" {
			v.add("list", "First: the OpenTelemetry Operator", "", j.operatorHint(t)...)
		}
		v.add("text", "1. Unpack the new files", "Download the files for this cluster below (they have changed since the first step) and unpack them over the old ones.")
		v.add("command", where, fmt.Sprintf("tar xzf %s.tar.gz", folder))
		v.add("text", "2. Run the installer", "It will ask you to type each secret. Typing is hidden.")
		v.add("command", where, fmt.Sprintf("cd %s && bash apply.sh", folder))
		v.add("text", "3. Paste what it printed", "From the line OTELGENIE-APPLY down to the line starting END OTELGENIE-APPLY.")
		v.Form = Form{Kind: "paste", Label: "Output of apply.sh"}

	case StepVerify:
		v.Title = "Check that data is flowing"
		v.Why = "The collectors are running. This step checks that each one is producing data and that it is reaching the collector endpoint. Wait about a minute after installing before running it."
		if t.Verify != nil && !t.Verify.Pass {
			j.explainVerify(v, t)
		}
		v.add("command", where, fmt.Sprintf("cd %s && bash verify.sh", folder))
		v.add("text", "", "Paste everything from the line OTELGENIE-VERIFY down to the line starting END OTELGENIE-VERIFY.")
		v.Form = Form{Kind: "paste", Label: "Output of verify.sh"}

	case StepDone:
		v.Title = "Telemetry is flowing from this cluster"
		v.Why = "Everything selected for this cluster is producing data and it is reaching the collector endpoint."
		if t.Verify != nil {
			v.Blocks = append(v.Blocks, verifyTable(t.Verify))
		}
		told := map[string]bool{}
		for _, e := range j.selectedEntries(t) {
			for _, n := range e.Needs {
				if n.Kind == "handout" && !told[n.Attrs["note"]] {
					told[n.Attrs["note"]] = true
					v.add("warn", "One thing left: "+e.Title, n.Attrs["note"])
				}
			}
		}
		v.Form = Form{Kind: "none"}
	}
}
